// Writes src/worker/build-info.ts with the commit SHA being built so the
// deployed Worker can report which commit it is running (/api/health).
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";

let sha = process.env.WORKERS_CI_COMMIT_SHA || process.env.GITHUB_SHA || "";
if (!sha) {
  try {
    sha = execSync("git rev-parse HEAD", { stdio: ["ignore", "pipe", "ignore"] }).toString().trim();
  } catch {
    sha = "unknown";
  }
}
const branch = process.env.WORKERS_CI_BRANCH || "";
const builtAt = new Date().toISOString();
const ci = process.env.WORKERS_CI ? "workers-builds" : "local";
writeFileSync(
  new URL("../src/worker/build-info.ts", import.meta.url),
  `// Generated by scripts/build-info.mjs — do not edit.\nexport const BUILD_INFO = ${JSON.stringify({ commit: sha, branch, builtAt, source: ci }, null, 2)} as const;\n`,
);
console.log(`build-info: ${sha} (${ci})`);
