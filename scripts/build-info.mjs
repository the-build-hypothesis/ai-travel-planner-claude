// Writes src/worker/build-info.ts with the commit SHA being built so the
// deployed Worker can report which commit it is running (/api/health).
// The file is only rewritten when the commit changes, so `wrangler dev`'s file
// watcher doesn't loop (the build command runs on every rebuild).
import { execSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";

let sha = process.env.WORKERS_CI_COMMIT_SHA || process.env.GITHUB_SHA || "";
if (!sha) {
  try {
    sha = execSync("git rev-parse HEAD", { stdio: ["ignore", "pipe", "ignore"] }).toString().trim();
  } catch {
    sha = "unknown";
  }
}
const branch = process.env.WORKERS_CI_BRANCH || "";
const source = process.env.WORKERS_CI ? "workers-builds" : "local";
const target = new URL("../src/worker/build-info.ts", import.meta.url);

if (existsSync(target)) {
  const current = readFileSync(target, "utf8");
  if (current.includes(`"commit": "${sha}"`) && current.includes(`"source": "${source}"`)) {
    console.log(`build-info: ${sha} (${source}, unchanged)`);
    process.exit(0);
  }
}
const info = { commit: sha, branch, builtAt: new Date().toISOString(), source };
writeFileSync(target, `// Generated by scripts/build-info.mjs — do not edit.\nexport const BUILD_INFO = ${JSON.stringify(info, null, 2)} as const;\n`);
console.log(`build-info: ${sha} (${source})`);
